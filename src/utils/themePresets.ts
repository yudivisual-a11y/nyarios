export function applyThemeVariables(theme: ColorTheme) {
  if (typeof document === 'undefined') return;
  const root = document.documentElement;

  root.style.setProperty('--bg-primary', theme.bgPrimary);
  root.style.setProperty('--bg-surface', theme.bgSurface);
  root.style.setProperty('--bg-card', theme.bgCard);
  root.style.setProperty('--bg-inset', theme.bgInset);
  root.style.setProperty('--text-primary', theme.textPrimary);
  root.style.setProperty('--text-secondary', theme.textSecondary);
  root.style.setProperty('--border-color', theme.borderColor);
  root.style.setProperty('--color-accent-primary', theme.primary);
  root.style.setProperty('--color-accent-hover', theme.hover);
  root.style.setProperty('--color-accent-from', theme.from);
  root.style.setProperty('--color-accent-to', theme.to);
  root.style.setProperty('--color-accent-shadow', theme.shadow);
  root.style.setProperty('--color-accent-glow', theme.glow);
  root.style.setProperty('--coral-accent', theme.primary);
  root.style.setProperty('--shadow-raised', theme.shadowRaised);
  root.style.setProperty('--shadow-flat', theme.shadowFlat);
  root.style.setProperty('--shadow-inset', theme.shadowInset);

  if (theme.isLight) {
    root.classList.remove('dark');
  } else {
    root.classList.add('dark');
  }
}
